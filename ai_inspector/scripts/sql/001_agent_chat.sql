-- Agent chat tables for the EXISTING private Inspector database.
-- Run as the schema owner/admin, e.g. the project's Supabase SQL Editor role.
-- Requires inspector.inspections/sessions/receipts and the inspector_app role.
-- No passwords, row deletion, data copying, sequence resets or role creation.
-- Repeatable for a compatible schema. An incompatible schema aborts atomically.

BEGIN;
SET LOCAL lock_timeout = '5s';
SET LOCAL statement_timeout = '30s';
SET LOCAL search_path = pg_catalog;

-- Same write lock as the native and Cloudflare Inspector adapters.
SELECT pg_advisory_xact_lock(7341202601);

DO $preflight$
BEGIN
    IF to_regnamespace('inspector') IS NULL
       OR to_regclass('inspector.inspections') IS NULL
       OR to_regclass('inspector.sessions') IS NULL
       OR to_regclass('inspector.receipts') IS NULL THEN
        RAISE EXCEPTION 'Existing Inspector database not found; check the selected project';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'inspector_app') THEN
        RAISE EXCEPTION 'Existing inspector_app role not found; apply the base server setup first';
    END IF;
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'inspector_app'
               AND (rolsuper OR rolcreaterole OR rolcreatedb OR rolbypassrls))
       OR has_schema_privilege('inspector_app', 'inspector', 'CREATE') THEN
        RAISE EXCEPTION 'inspector_app must be the existing restricted runtime role';
    END IF;
END
$preflight$;

CREATE TABLE IF NOT EXISTS inspector.chats (
    chat_id TEXT PRIMARY KEY,
    project_id TEXT NOT NULL,
    data TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS inspector.agent_runs (
    sequence BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id TEXT NOT NULL UNIQUE,
    chat_id TEXT NOT NULL REFERENCES inspector.chats(chat_id),
    request_id TEXT NOT NULL,
    request_body TEXT NOT NULL,
    data TEXT NOT NULL,
    lease_until DOUBLE PRECISION NOT NULL DEFAULT 0,
    lease_token TEXT,
    UNIQUE(chat_id, request_id)
);

-- IF NOT EXISTS alone does not prove an existing table matches the backend.
DO $validate$
DECLARE
    spec RECORD;
    relation_oid OID;
BEGIN
    FOR spec IN SELECT * FROM (VALUES ('chats', 3), ('agent_runs', 8)) AS t(table_name, column_count)
    LOOP
        relation_oid := format('inspector.%I', spec.table_name)::regclass;
        IF NOT EXISTS (SELECT 1 FROM pg_class WHERE oid = relation_oid
                       AND relkind = 'r' AND NOT relrowsecurity)
           OR (SELECT count(*) FROM pg_attribute WHERE attrelid = relation_oid
               AND attnum > 0 AND NOT attisdropped) <> spec.column_count THEN
            RAISE EXCEPTION 'Incompatible inspector.% table; review its schema manually', spec.table_name;
        END IF;
        IF EXISTS (SELECT 1 FROM pg_class WHERE oid = relation_oid
                   AND pg_has_role('inspector_app', relowner, 'USAGE')) THEN
            RAISE EXCEPTION 'Runtime role must not own or inherit ownership of inspector.%', spec.table_name;
        END IF;
    END LOOP;

    FOR spec IN SELECT * FROM (VALUES
        ('chats', 'chat_id', 'text', TRUE, ''),
        ('chats', 'project_id', 'text', TRUE, ''),
        ('chats', 'data', 'text', TRUE, ''),
        ('agent_runs', 'sequence', 'bigint', TRUE, 'd'),
        ('agent_runs', 'run_id', 'text', TRUE, ''),
        ('agent_runs', 'chat_id', 'text', TRUE, ''),
        ('agent_runs', 'request_id', 'text', TRUE, ''),
        ('agent_runs', 'request_body', 'text', TRUE, ''),
        ('agent_runs', 'data', 'text', TRUE, ''),
        ('agent_runs', 'lease_until', 'double precision', TRUE, ''),
        ('agent_runs', 'lease_token', 'text', FALSE, '')
    ) AS t(table_name, column_name, type_name, not_null, identity_kind)
    LOOP
        IF NOT EXISTS (
            SELECT 1 FROM pg_attribute
            WHERE attrelid = format('inspector.%I', spec.table_name)::regclass
              AND attname = spec.column_name AND NOT attisdropped
              AND atttypid = spec.type_name::regtype
              AND attnotnull = spec.not_null AND attidentity::text = spec.identity_kind
        ) THEN
            RAISE EXCEPTION 'Incompatible inspector.%.% column', spec.table_name, spec.column_name;
        END IF;
    END LOOP;

    FOR spec IN SELECT * FROM (VALUES
        ('chats', 'p', ARRAY['chat_id']),
        ('agent_runs', 'p', ARRAY['sequence']),
        ('agent_runs', 'u', ARRAY['run_id']),
        ('agent_runs', 'u', ARRAY['chat_id', 'request_id']),
        ('agent_runs', 'f', ARRAY['chat_id'])
    ) AS t(table_name, constraint_kind, column_names)
    LOOP
        relation_oid := format('inspector.%I', spec.table_name)::regclass;
        IF NOT EXISTS (
            SELECT 1 FROM pg_constraint c
            WHERE c.conrelid = relation_oid AND c.contype::text = spec.constraint_kind
              AND c.convalidated AND NOT c.condeferrable
              AND c.conkey = ARRAY(
                  SELECT a.attnum FROM unnest(spec.column_names) WITH ORDINALITY AS n(name, position)
                  JOIN pg_attribute a ON a.attrelid = relation_oid AND a.attname = n.name
                  ORDER BY n.position
              )
              AND (c.contype <> 'f' OR (
                  c.confrelid = 'inspector.chats'::regclass
                  AND c.confkey = ARRAY(SELECT attnum FROM pg_attribute
                      WHERE attrelid = 'inspector.chats'::regclass AND attname = 'chat_id')
                  AND c.confdeltype = 'a' AND c.confupdtype = 'a'
              ))
        ) THEN
            RAISE EXCEPTION 'Required constraint missing on inspector.% (%)', spec.table_name, spec.column_names;
        END IF;
    END LOOP;
END
$validate$;

CREATE INDEX IF NOT EXISTS runs_by_chat ON inspector.agent_runs(chat_id, sequence);
ALTER TABLE inspector.agent_runs ALTER COLUMN lease_until SET DEFAULT 0;
ALTER TABLE inspector.agent_runs ALTER COLUMN lease_token DROP DEFAULT;

-- Only these two tables and their identity sequence receive new ACLs.
-- Existing capture tables, their grants, and Storage policies are untouched.
REVOKE ALL ON TABLE inspector.chats, inspector.agent_runs FROM PUBLIC, inspector_app;
REVOKE ALL (chat_id, project_id, data) ON TABLE inspector.chats FROM PUBLIC, inspector_app;
REVOKE ALL (sequence, run_id, chat_id, request_id, request_body, data, lease_until, lease_token)
    ON TABLE inspector.agent_runs FROM PUBLIC, inspector_app;
GRANT USAGE ON SCHEMA inspector TO inspector_app;
GRANT SELECT, INSERT, UPDATE ON TABLE inspector.chats, inspector.agent_runs TO inspector_app;

DO $permissions$
DECLARE
    run_sequence REGCLASS;
    client_role TEXT;
BEGIN
    run_sequence := pg_get_serial_sequence('inspector.agent_runs', 'sequence')::regclass;
    IF run_sequence IS NULL THEN
        RAISE EXCEPTION 'Agent run identity sequence not found';
    END IF;
    EXECUTE format('REVOKE ALL ON SEQUENCE %s FROM PUBLIC, inspector_app', run_sequence);
    EXECUTE format('GRANT USAGE, SELECT ON SEQUENCE %s TO inspector_app', run_sequence);
    IF has_table_privilege('inspector_app', 'inspector.chats', 'DELETE,TRUNCATE,REFERENCES,TRIGGER')
       OR has_table_privilege('inspector_app', 'inspector.agent_runs', 'DELETE,TRUNCATE,REFERENCES,TRIGGER')
       OR has_any_column_privilege('inspector_app', 'inspector.chats', 'REFERENCES')
       OR has_any_column_privilege('inspector_app', 'inspector.agent_runs', 'REFERENCES')
       OR has_sequence_privilege('inspector_app', run_sequence, 'UPDATE') THEN
        RAISE EXCEPTION 'Runtime role still inherits unsupported chat privileges; review role memberships';
    END IF;
    FOREACH client_role IN ARRAY ARRAY['anon', 'authenticated']
    LOOP
        IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = client_role) THEN
            EXECUTE format('REVOKE ALL ON TABLE inspector.chats, inspector.agent_runs FROM %I', client_role);
            EXECUTE format('REVOKE ALL (chat_id, project_id, data) ON TABLE inspector.chats FROM %I', client_role);
            EXECUTE format('REVOKE ALL (sequence, run_id, chat_id, request_id, request_body, data, lease_until, lease_token) ON TABLE inspector.agent_runs FROM %I', client_role);
            EXECUTE format('REVOKE ALL ON SEQUENCE %s FROM %I', run_sequence, client_role);
            IF has_table_privilege(client_role, 'inspector.chats', 'SELECT,INSERT,UPDATE,DELETE,TRUNCATE,REFERENCES,TRIGGER')
               OR has_table_privilege(client_role, 'inspector.agent_runs', 'SELECT,INSERT,UPDATE,DELETE,TRUNCATE,REFERENCES,TRIGGER')
               OR has_any_column_privilege(client_role, 'inspector.chats', 'SELECT,INSERT,UPDATE,REFERENCES')
               OR has_any_column_privilege(client_role, 'inspector.agent_runs', 'SELECT,INSERT,UPDATE,REFERENCES')
               OR has_sequence_privilege(client_role, run_sequence, 'USAGE,SELECT,UPDATE') THEN
                RAISE EXCEPTION 'Browser role % still inherits private chat access; review role memberships', client_role;
            END IF;
        END IF;
    END LOOP;
END
$permissions$;

COMMIT;

-- Read-only result for the SQL Editor. All three access flags must be true.
SELECT table_name,
       pg_catalog.has_table_privilege('inspector_app', pg_catalog.format('inspector.%I', table_name), 'SELECT') AS can_read,
       pg_catalog.has_table_privilege('inspector_app', pg_catalog.format('inspector.%I', table_name), 'INSERT') AS can_insert,
       pg_catalog.has_table_privilege('inspector_app', pg_catalog.format('inspector.%I', table_name), 'UPDATE') AS can_update
FROM (VALUES ('chats'), ('agent_runs')) AS t(table_name);

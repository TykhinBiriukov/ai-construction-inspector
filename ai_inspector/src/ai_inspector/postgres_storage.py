"""Private PostgreSQL persistence preserving the existing serialized-write contract."""
from contextlib import contextmanager
import re

import psycopg
from psycopg.rows import dict_row

from .errors import APIError
from .storage import Database, SCHEMA_SQL

# Shared by all replicas and the migration tool. Equivalent to SQLite BEGIN IMMEDIATE.
WRITE_LOCK = 7341202601
TABLES = ('inspections', 'sessions', 'receipts', 'capture_completions', 'geometry_jobs',
          'work_items', 'device_events', 'device_connections', 'upload_requests',
          'upload_objects', 'geometry_events', 'chats', 'agent_runs', 'backlog_items')


class Row(dict):
    def __getitem__(self, key):
        return tuple(self.values())[key] if isinstance(key, int) else super().__getitem__(key)


def row_factory(cursor):
    factory = dict_row(cursor)
    return lambda values: Row(factory(values))


class Connection:
    def __init__(self, raw):
        self.raw = raw

    def execute(self, query, parameters=()):
        # Only server-owned SQL uses this adapter. Values always remain bound parameters.
        if query.strip() == 'BEGIN':
            query = 'BEGIN ISOLATION LEVEL REPEATABLE READ READ ONLY'
        if query.startswith('INSERT OR IGNORE INTO '):
            query = query.replace('INSERT OR IGNORE INTO ', 'INSERT INTO ', 1) + ' ON CONFLICT DO NOTHING'
        return self.raw.execute(query.replace('?', '%s'), parameters or None)

    def commit(self):
        self.raw.commit()

    def rollback(self):
        self.raw.rollback()


class PostgresDatabase(Database):
    def __init__(self, url, *, initialize=True):
        self._url = url
        if initialize:
            with self.transaction() as connection:
                connection.execute('CREATE SCHEMA IF NOT EXISTS inspector')
                connection.execute('REVOKE ALL ON SCHEMA inspector FROM PUBLIC')
                ddl = SCHEMA_SQL.replace('INTEGER PRIMARY KEY AUTOINCREMENT', 'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY')
                ddl = re.sub(r'\bREAL\b', 'DOUBLE PRECISION', ddl)
                # SQLite's implicit rowid is explicit for deterministic ordering.
                for table in ('inspections', 'work_items'):
                    ddl = ddl.replace(f'CREATE TABLE IF NOT EXISTS {table} (',
                                      f'CREATE TABLE IF NOT EXISTS {table} (rowid BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,')
                for statement in ddl.split(';'):
                    if statement.strip():
                        connection.execute(statement)
                connection.execute('REVOKE ALL ON ALL TABLES IN SCHEMA inspector FROM PUBLIC')
                # Supabase's browser roles must not be able to read server metadata.
                for role in ('anon', 'authenticated'):
                    if connection.execute('SELECT 1 FROM pg_roles WHERE rolname=?', (role,)).fetchone():
                        connection.execute(f'REVOKE ALL ON SCHEMA inspector FROM {role}')
                        connection.execute(f'REVOKE ALL ON ALL TABLES IN SCHEMA inspector FROM {role}')

    @contextmanager
    def connection(self):
        try:
            with psycopg.connect(self._url, autocommit=True, connect_timeout=15,
                                 prepare_threshold=None, row_factory=row_factory) as raw:
                raw.execute('SET search_path TO inspector')
                raw.execute('SET extra_float_digits TO 3')
                raw.execute("SET lock_timeout = '30s'")
                raw.execute("SET statement_timeout = '60s'")
                try:
                    yield Connection(raw)
                finally:
                    # Close a read snapshot without leaking an open transaction to the pooler.
                    if raw.info.transaction_status == psycopg.pq.TransactionStatus.INTRANS:
                        raw.execute('ROLLBACK')
        except (psycopg.OperationalError, psycopg.InterfaceError):
            raise APIError(503, 'storage_unavailable', 'Database is temporarily unavailable', retryable=True) from None

    @contextmanager
    def transaction(self):
        with self.connection() as connection:
            with connection.raw.transaction():
                connection.execute('SELECT pg_advisory_xact_lock(?)', (WRITE_LOCK,))
                yield connection
